def test_every_script_invoked_exists(code_src):
    for script in set(re.findall(r'"(scripts/[\w./-]+\.py)"', code_src)):
        assert (ROOT / script).exists(), f"{script} does not exist"


def test_every_flag_is_defined_by_its_script(code_src):
    """A flag the target does not define aborts the stage instantly."""
    for call in re.findall(r'run\((.*?)\)\n', code_src, re.S):
        scripts = re.findall(r'"(scripts/[\w./-]+\.py)"', call)
        if not scripts:
            continue
        body = (ROOT / scripts[0]).read_text()
        for flag in re.findall(r'"(--[\w-]+)"', call):
            assert f'"{flag}"' in body, \
                f"{scripts[0]} does not define {flag}"


def test_run_study_is_called_with_one_corpus_at_a_time(code_src):
    """run_study.py refuses corpora needing different caps; respect that."""
    for call in re.findall(r'run\((.*?)\)\n', code_src, re.S):
        if "run_study.py" not in call:
            continue
        # The generated cell loops over CORPORA one at a time.
        assert "--datasets" in call
        assert "corpus" in call or call.count('"ml_1m"') <= 1, \
            "run_study.py must receive a single corpus per invocation"


