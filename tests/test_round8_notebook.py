"""The round-8 notebook must stay in sync with the scripts it drives.

A notebook is the easiest artefact in the repository to break silently: it is
edited in a GUI, its diff is unreadable, and nothing compiles it. This one
launches multi-hour runs on the user's machine, so a mistyped flag or a stale
corpus name costs real time before anyone notices.

Two defences. The notebook is GENERATED by `scripts/make_round8_notebook.py`,
and these tests assert the checked-in file is exactly what that script
produces, so an in-Jupyter edit that was not regenerated fails CI. Everything
else here checks the properties that would waste a run.
"""
from __future__ import annotations

import ast
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "notebooks" / "SignalShap_Round8_Runs.ipynb"
GEN = ROOT / "scripts" / "make_round8_notebook.py"

PAPER_CORPORA = ("ml_1m", "amazon_video_games", "gowalla_ts")
# The untimestamped LightGCN splits. Correct for the other notebook, wrong
# here: running them would produce artefacts for corpora the paper does not
# report, which is worse than producing none.
WRONG_CORPORA = ("yelp2018", "amazon_book_lgcn", "lastfm_2k", "amazon_book")


@pytest.fixture(scope="module")
def nb() -> dict:
    return json.loads(NB.read_text())


@pytest.fixture(scope="module")
def code_src(nb) -> str:
    return "\n".join("".join(c["source"])
                     for c in nb["cells"] if c["cell_type"] == "code")


def test_notebook_matches_its_generator():
    """Catch an edit made in Jupyter and committed without regenerating.

    The generator must NOT be allowed to overwrite the checked-in file before
    the comparison: an earlier version of this test did exactly that and could
    therefore never fail. Import the generator and build the notebook in
    memory instead, leaving the file on disk untouched.
    """
    import importlib.util

    spec = importlib.util.spec_from_file_location("_gen_r8", GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    # Compare SOURCE only. A committed run legitimately carries outputs and
    # execution counts, and those must not be mistaken for drift; the thing
    # that must never diverge silently is the code being executed.
    def sources(nbdict):
        # Jupyter appends a trailing empty cell when a notebook is saved from
        # the UI. That is not drift, so empty cells are dropped before the
        # comparison.
        return [("".join(c["source"]), c["cell_type"]) for c in nbdict["cells"]
                if "".join(c["source"]).strip()]

    expected = sources(mod.build())
    actual = sources(json.loads(NB.read_text()))
    assert actual == expected, (
        "notebooks/SignalShap_Round8_Runs.ipynb differs from what "
        "scripts/make_round8_notebook.py produces. Edit the generator, then "
        "run `python scripts/make_round8_notebook.py`.")


def test_generation_is_deterministic():
    """Cell ids are content-hashed, so regeneration must be a no-op diff."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("_gen_r8b", GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    assert json.dumps(mod.build(), indent=1) == json.dumps(mod.build(), indent=1)


def test_every_code_cell_parses(nb):
    for i, c in enumerate(nb["cells"]):
        if c["cell_type"] != "code":
            continue
        src = "".join(c["source"])
        if src.lstrip().startswith("%"):      # magics are not python
            continue
        try:
            ast.parse(src)
        except SyntaxError as e:
            pytest.fail(f"cell {i} does not parse: {e}")


def test_notebook_is_valid_nbformat_with_ids(nb):
    assert nb["nbformat"] == 4 and nb["nbformat_minor"] >= 5
    ids = [c["id"] for c in nb["cells"]]
    assert all(ids), "every cell needs an id at nbformat 4.5+"
    assert len(set(ids)) == len(ids), "cell ids must be unique"


def test_only_the_papers_corpora_are_run(code_src):
    """The M4 notebook runs different corpora; this one must not."""
    for wrong in WRONG_CORPORA:
        assert wrong not in code_src, (
            f"{wrong!r} is not a corpus this paper reports; running it "
            f"produces artefacts for the wrong dataset")
